//! Curated, admission-gated **parts library** (BAR.md, I7) — the growing,
//! AI-extensible catalog of `.lmcpart` entries.
//!
//! A [`Library`] is a plain directory: one `.lmcpart` file per admitted entry
//! plus a byte-stable `index.json` (every JSON object written with sorted keys,
//! entries sorted by `(name, version)`), so the whole library is git-versioned
//! data — every admission, deprecation and removal is auditable and reversible
//! through ordinary version control.
//!
//! ## The admission gate (no pollution)
//! [`Library::add`] accepts a candidate part ONLY after it proves itself at a
//! deterministic sample set of its **declared parameter interface**
//! ([`ParamSpec`]: units / default / min / max per parameter):
//!
//! - the **defaults** sample, every **range corner** (all `2^n` min/max
//!   combinations, capped — default 16 — by a deterministic spread that always
//!   keeps all-min, all-max and each single-parameter extreme), and the
//!   **midpoint**;
//! - each sample must rebuild to a **closed manifold** B-rep, and rebuild
//!   **volume-bit-deterministically** (two full evaluations must agree to the
//!   last bit);
//! - per-sample measures (volume, face count, genus, shells) are recorded in
//!   the entry's [`GateSummary`] as evidence.
//!
//! A failing candidate is rejected with a loud [`AdmissionError`] naming the
//! exact failing sample and its parameter values — never a silent skip. Honest
//! scope: the gate proves validity and determinism **at the sampled points**,
//! not across the whole continuous range between them.
//!
//! ## Curation lifecycle (user and AI share control)
//! - [`Library::search`] finds entries by free text and tags; **deprecated
//!   entries are hidden** from search.
//! - [`Library::instantiate`] builds a fresh [`Document`] from a stored entry
//!   with caller parameters, loudly rejecting unknown names/versions, unknown
//!   parameters and out-of-range values. A deprecated entry still instantiates
//!   (existing designs keep building) but the result **warns** via
//!   [`Instantiated::deprecated`].
//! - [`Library::deprecate`] hides a name from search without touching files.
//! - [`Library::remove`] deletes a name's files and index rows, but **refuses
//!   with the dependent list** ([`LibraryError::DependentsExist`]) when any
//!   `.lmcasm` in the directory still references one of them by path — unless
//!   `force` is passed (git history keeps the removal recoverable).
//!
//! Dates are **caller-supplied** ([`Provenance::date`]): this module never
//! reads a clock, so identical inputs always produce identical bytes.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt;
use std::path::{Component, Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::format::{self, FormatError};
use crate::Document;

/// The `format` tag of a library `index.json`.
pub const LIBRARY_INDEX_FORMAT: &str = "lmc-library-index";
/// The (single) index version this kernel writes and reads.
pub const LIBRARY_INDEX_VERSION: u32 = 1;
/// File name of the index inside the library directory.
pub const INDEX_FILE: &str = "index.json";
/// How many full rebuilds the admission gate compares for bit-determinism.
pub const GATE_REBUILDS: u32 = 2;

/// One declared parameter of an entry's public interface: the name an
/// [`Library::instantiate`] caller may set, its units, its default and its
/// admissible `[min, max]` range (both inclusive; `min == max` pins it).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct ParamSpec {
	/// Parameter name — must exist in the part document's parameter table.
	pub name: String,
	/// Units of the value (`"mm"`, `"deg"`, `"count"`, …); declared, not converted.
	pub units: String,
	/// The default value, used for unset parameters on instantiate.
	pub default: f64,
	/// Inclusive lower bound of admissible values.
	pub min: f64,
	/// Inclusive upper bound of admissible values.
	pub max: f64,
	/// What the parameter means (may be empty).
	#[serde(default)]
	pub description: String,
}

/// Who/what authored an entry and when. The `date` is **supplied by the
/// caller** (e.g. `"2026-06-10"`) — the library never reads a clock, keeping
/// every write reproducible byte-for-byte.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Provenance {
	/// Who authored the part (a person, an AI session, a pipeline id).
	pub author: String,
	/// What produced the part file (tool + version).
	pub created_with: String,
	/// Caller-supplied creation date string; never generated by this module.
	pub date: String,
}

/// The caller-supplied metadata of a candidate entry for [`Library::add`].
#[derive(Clone, Debug, PartialEq)]
pub struct EntryMeta {
	/// Library name of the part (also the stored file stem):
	/// 1–64 chars of `A–Z a–z 0–9 . _ -`, starting alphanumeric.
	pub name: String,
	/// Version of this entry, `≥ 1`. One `(name, version)` is immutable once
	/// admitted; changed geometry must be admitted as a new version.
	pub version: u32,
	/// Coarse grouping for search (`"bearings"`, `"brackets"`, …; may be empty).
	pub category: String,
	/// Search tags (sorted + deduplicated on admission).
	pub tags: Vec<String>,
	/// Free-text description (searched).
	pub description: String,
	/// Authorship record; `date` comes from the caller, never from a clock.
	pub provenance: Provenance,
	/// The declared public parameter interface (may be empty for a fixed part).
	pub param_interface: Vec<ParamSpec>,
}

/// Options of [`Library::add`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AddOptions {
	/// Maximum number of range-corner samples the gate builds (`≥ 2`; default
	/// 16). With `n` interface parameters the gate uses all `2^n` corners when
	/// they fit, else a deterministic spread of `corner_cap` corners that always
	/// contains all-min, all-max, and each single-parameter extreme (parameters
	/// beyond the cap's reach are still exercised by all-min/all-max).
	pub corner_cap: usize,
}

impl Default for AddOptions {
	fn default() -> Self {
		AddOptions { corner_cap: 16 }
	}
}

/// The recorded measures of one admission-gate sample.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct GateSample {
	/// `"defaults"`, `"midpoint"`, or `"corner_<l|h per parameter>"` (interface
	/// order; `l` = min, `h` = max).
	pub label: String,
	/// The exact parameter values of this sample.
	pub params: BTreeMap<String, f64>,
	/// Mesh-faceted enclosed volume of the rebuilt solid (bit-identical across
	/// the gate's rebuilds — that is what the gate proved).
	pub volume: f64,
	/// Face count of the rebuilt solid.
	pub faces: usize,
	/// Genus of the rebuilt solid.
	pub genus: i64,
	/// Shell count of the rebuilt solid.
	pub shells: usize,
}

/// The evidence an entry passed admission: which samples were built and what
/// they measured. `rebuilds` is the number of full evaluations compared for
/// volume-bit-determinism (always [`GATE_REBUILDS`]).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct GateSummary {
	/// Full rebuilds compared per sample (volume bits must match exactly).
	pub rebuilds: u32,
	/// The corner cap the gate ran with (see [`AddOptions::corner_cap`]).
	pub corner_cap: usize,
	/// Every sample built, in gate order (defaults, corners, midpoint).
	pub samples: Vec<GateSample>,
}

/// One admitted library entry, exactly as stored in `index.json`.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Entry {
	/// Library name (see [`EntryMeta::name`]).
	pub name: String,
	/// Version (see [`EntryMeta::version`]).
	pub version: u32,
	/// Coarse grouping for search.
	pub category: String,
	/// Search tags, sorted and deduplicated.
	pub tags: Vec<String>,
	/// Free-text description.
	pub description: String,
	/// Authorship record (caller-supplied date).
	pub provenance: Provenance,
	/// The declared public parameter interface.
	pub param_interface: Vec<ParamSpec>,
	/// The admission-gate evidence this entry was accepted on.
	pub admitted: GateSummary,
	/// The stored `.lmcpart` file name, relative to the library directory.
	pub file: String,
	/// Whether the entry is deprecated (hidden from search; instantiate warns).
	#[serde(default, skip_serializing_if = "std::ops::Not::not")]
	pub deprecated: bool,
}

/// A successful [`Library::instantiate`]: the rebuilt parametric [`Document`]
/// plus what it was built from. `deprecated` is the **warning channel**
/// required by BAR.md I7 — a deprecated entry still builds, but the caller is
/// told so it can surface the warning instead of silently shipping a part the
/// curators retired.
#[derive(Clone, Debug)]
pub struct Instantiated {
	/// The part document: interface defaults applied, then the caller's values.
	pub document: Document,
	/// The entry's name.
	pub name: String,
	/// The entry version that was instantiated.
	pub version: u32,
	/// True when the entry is deprecated — the build is fine, but warn the user.
	pub deprecated: bool,
}

// --- Errors --------------------------------------------------------------------------

/// Why [`Library::add`] refused a candidate. Every variant names exactly what
/// is wrong; gate failures name the failing **sample** (label + parameter
/// values) so the author can reproduce it.
#[derive(Debug)]
pub enum AdmissionError {
	/// The metadata is malformed: bad name, version 0, inconsistent ranges,
	/// an interface parameter the document does not declare, … (the reason
	/// string is precise).
	BadMeta {
		/// What exactly is malformed.
		reason: String,
	},
	/// This `(name, version)` is already admitted — entries are immutable;
	/// admit changed geometry as a new version.
	DuplicateEntry {
		/// The colliding name.
		name: String,
		/// The colliding version.
		version: u32,
	},
	/// The candidate `part_json` is not a loadable `.lmcpart`.
	BadPart {
		/// The underlying format error.
		error: FormatError,
	},
	/// A gate sample failed to build: the feature tree produced no exact B-rep
	/// (or an empty solid) at those parameter values.
	GateBuildFailed {
		/// The failing sample: label plus its exact parameter values.
		sample: String,
		/// Why the build failed.
		reason: String,
	},
	/// A gate sample built but is not a closed manifold.
	GateInvalid {
		/// The failing sample: label plus its exact parameter values.
		sample: String,
		/// Whether the rebuilt boundary was closed.
		closed: bool,
		/// Whether the rebuilt boundary was manifold.
		manifold: bool,
		/// Genus of the rebuilt boundary.
		genus: i64,
		/// Shell count of the rebuilt boundary.
		shells: usize,
	},
	/// A gate sample did not rebuild volume-bit-deterministically: two full
	/// evaluations disagreed.
	GateNondeterministic {
		/// The failing sample: label plus its exact parameter values.
		sample: String,
		/// Volume of the first build.
		first_volume: f64,
		/// Volume of the second build.
		second_volume: f64,
	},
	/// A library file could not be written (the gate may already have passed;
	/// nothing was admitted).
	Io {
		/// The path that failed.
		path: PathBuf,
		/// The underlying I/O error.
		error: std::io::Error,
	},
}

impl fmt::Display for AdmissionError {
	fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
		match self {
			AdmissionError::BadMeta { reason } => write!(f, "bad entry metadata: {reason}"),
			AdmissionError::DuplicateEntry { name, version } => {
				write!(f, "'{name}' v{version} is already admitted — entries are immutable, admit the change as a new version")
			}
			AdmissionError::BadPart { error } => write!(f, "candidate is not a loadable .lmcpart: {error}"),
			AdmissionError::GateBuildFailed { sample, reason } => {
				write!(f, "admission gate: sample {sample} failed to build: {reason}")
			}
			AdmissionError::GateInvalid { sample, closed, manifold, genus, shells } => {
				write!(
					f,
					"admission gate: sample {sample} is not a closed manifold (closed={closed} manifold={manifold} genus={genus} shells={shells})"
				)
			}
			AdmissionError::GateNondeterministic { sample, first_volume, second_volume } => {
				write!(
					f,
					"admission gate: sample {sample} did not rebuild bit-deterministically (volume {first_volume:?} vs {second_volume:?})"
				)
			}
			AdmissionError::Io { path, error } => write!(f, "cannot write library file '{}': {error}", path.display()),
		}
	}
}

impl std::error::Error for AdmissionError {
	fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
		match self {
			AdmissionError::BadPart { error } => Some(error),
			AdmissionError::Io { error, .. } => Some(error),
			_ => None,
		}
	}
}

/// Why a library operation (open / instantiate / deprecate / remove) failed.
#[derive(Debug)]
pub enum LibraryError {
	/// A library file could not be read or written.
	Io {
		/// The path that failed.
		path: PathBuf,
		/// The underlying I/O error.
		error: std::io::Error,
	},
	/// `index.json` exists but is not a loadable library index (wrong format
	/// tag, unsupported version, duplicate entries, unsafe file names, or not
	/// JSON at all).
	IndexCorrupt {
		/// The index path.
		path: PathBuf,
		/// What exactly is wrong.
		reason: String,
	},
	/// No entry with this name exists; lists what does.
	UnknownPart {
		/// The requested name.
		name: String,
		/// All names the library currently holds (sorted, deduplicated).
		available: Vec<String>,
	},
	/// The name exists, but not at the requested version; lists its versions.
	UnknownVersion {
		/// The requested name.
		name: String,
		/// The requested version.
		version: u32,
		/// The versions that exist for this name (ascending).
		available: Vec<u32>,
	},
	/// An instantiate parameter is not part of the entry's declared interface.
	UnknownParam {
		/// The entry being instantiated.
		part: String,
		/// The offending parameter name.
		param: String,
		/// The declared interface parameter names (interface order).
		interface: Vec<String>,
	},
	/// An instantiate value is outside the declared `[min, max]` range (or not
	/// finite).
	OutOfRange {
		/// The entry being instantiated.
		part: String,
		/// The offending parameter name.
		param: String,
		/// The offending value.
		value: f64,
		/// Declared inclusive minimum.
		min: f64,
		/// Declared inclusive maximum.
		max: f64,
	},
	/// A stored `.lmcpart` failed to load back (the directory was edited by
	/// hand or corrupted).
	BadStoredPart {
		/// The stored part path.
		path: PathBuf,
		/// The underlying format error.
		error: FormatError,
	},
	/// A `.lmcasm` in the library directory could not be checked for
	/// dependencies (unreadable JSON) — removal refuses rather than guessing.
	AsmUnreadable {
		/// The assembly file path.
		path: PathBuf,
		/// Why it could not be checked.
		reason: String,
	},
	/// [`Library::remove`] refused: these `.lmcasm` files (relative to the
	/// library directory, sorted) still reference the entry's part files by
	/// path. Pass `force: true` to remove anyway (git history keeps the
	/// removal recoverable).
	DependentsExist {
		/// The name being removed.
		name: String,
		/// The referencing `.lmcasm` file names.
		dependents: Vec<String>,
	},
}

impl fmt::Display for LibraryError {
	fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
		match self {
			LibraryError::Io { path, error } => write!(f, "cannot access '{}': {error}", path.display()),
			LibraryError::IndexCorrupt { path, reason } => {
				write!(f, "'{}' is not a loadable library index: {reason}", path.display())
			}
			LibraryError::UnknownPart { name, available } => {
				write!(
					f,
					"no library entry named '{name}' (available: {})",
					if available.is_empty() { "none".to_string() } else { available.join(", ") }
				)
			}
			LibraryError::UnknownVersion { name, version, available } => {
				let versions: Vec<String> = available.iter().map(|v| format!("v{v}")).collect();
				write!(f, "'{name}' has no version {version} (available: {})", versions.join(", "))
			}
			LibraryError::UnknownParam { part, param, interface } => {
				write!(
					f,
					"'{part}' declares no parameter '{param}' (interface: {})",
					if interface.is_empty() { "none — this entry takes no parameters".to_string() } else { interface.join(", ") }
				)
			}
			LibraryError::OutOfRange { part, param, value, min, max } => {
				write!(f, "'{part}' parameter '{param}': {value} is outside the declared range [{min}, {max}]")
			}
			LibraryError::BadStoredPart { path, error } => {
				write!(f, "stored part '{}' failed to load: {error}", path.display())
			}
			LibraryError::AsmUnreadable { path, reason } => {
				write!(f, "cannot check '{}' for dependents: {reason}", path.display())
			}
			LibraryError::DependentsExist { name, dependents } => {
				write!(
					f,
					"refusing to remove '{name}': referenced by {} (pass force to remove anyway; git history keeps it recoverable)",
					dependents.join(", ")
				)
			}
		}
	}
}

impl std::error::Error for LibraryError {
	fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
		match self {
			LibraryError::Io { error, .. } => Some(error),
			LibraryError::BadStoredPart { error, .. } => Some(error),
			_ => None,
		}
	}
}

// --- The index file ---------------------------------------------------------------------

/// Serde mirror of `index.json` (the contract fields are `Option` so a foreign
/// file reports "missing" precisely).
#[derive(Serialize, Deserialize)]
struct IndexFile {
	format: Option<String>,
	version: Option<u32>,
	#[serde(default)]
	entries: Vec<Entry>,
}

/// Serialize `value` with **every JSON object's keys sorted** (serde_json's
/// default `Map` is a `BTreeMap`, so routing through a `Value` canonicalizes
/// key order) — the byte-stable form all library writes use. All floats are
/// validated finite before they get here.
fn canonical_json<T: Serialize>(value: &T) -> String {
	let v = serde_json::to_value(value).expect("library data serializes: string keys, finite floats");
	serde_json::to_string_pretty(&v).expect("a serde_json::Value pretty-prints")
}

// --- The library ---------------------------------------------------------------------------

/// A curated parts library on disk: a directory of admitted `.lmcpart` files
/// plus a byte-stable `index.json`. See the [module docs](self) for the
/// admission gate and the curation lifecycle.
pub struct Library {
	dir: PathBuf,
	/// All entries, sorted by `(name, version)` — including deprecated ones.
	entries: Vec<Entry>,
}

impl Library {
	/// Open the library at `dir`, creating the directory if needed. A missing
	/// `index.json` is an empty library; a present but unreadable/foreign one is
	/// a loud [`LibraryError::IndexCorrupt`] (never half-loads). Hand-edited
	/// indexes are checked: duplicate `(name, version)` rows and `file` fields
	/// that are not plain file names (no `/`, no `..`) are refused.
	pub fn open(dir: impl AsRef<Path>) -> Result<Library, LibraryError> {
		let dir = dir.as_ref().to_path_buf();
		std::fs::create_dir_all(&dir).map_err(|error| LibraryError::Io { path: dir.clone(), error })?;
		let index_path = dir.join(INDEX_FILE);
		let mut entries = match std::fs::read_to_string(&index_path) {
			Err(e) if e.kind() == std::io::ErrorKind::NotFound => Vec::new(),
			Err(error) => return Err(LibraryError::Io { path: index_path, error }),
			Ok(text) => {
				let corrupt = |reason: String| LibraryError::IndexCorrupt { path: index_path.clone(), reason };
				let file: IndexFile = serde_json::from_str(&text).map_err(|e| corrupt(e.to_string()))?;
				match file.format.as_deref() {
					Some(LIBRARY_INDEX_FORMAT) => {}
					found => return Err(corrupt(format!("expected format \"{LIBRARY_INDEX_FORMAT}\", found {found:?}"))),
				}
				if file.version != Some(LIBRARY_INDEX_VERSION) {
					return Err(corrupt(format!("expected version {LIBRARY_INDEX_VERSION}, found {:?}", file.version)));
				}
				let mut seen = BTreeSet::new();
				for entry in &file.entries {
					if !seen.insert((entry.name.clone(), entry.version)) {
						return Err(corrupt(format!("duplicate entry '{}' v{}", entry.name, entry.version)));
					}
					let mut components = Path::new(&entry.file).components();
					let plain = matches!(components.next(), Some(Component::Normal(_))) && components.next().is_none();
					if !plain {
						return Err(corrupt(format!(
							"entry '{}' v{}: file '{}' is not a plain file name inside the library directory",
							entry.name, entry.version, entry.file
						)));
					}
				}
				file.entries
			}
		};
		entries.sort_by(|a, b| (a.name.as_str(), a.version).cmp(&(b.name.as_str(), b.version)));
		Ok(Library { dir, entries })
	}

	/// The directory this library lives in.
	pub fn dir(&self) -> &Path {
		&self.dir
	}

	/// Every entry — **including deprecated ones** — sorted by `(name, version)`.
	/// Use [`Library::search`] for the curated (deprecation-hidden) view.
	pub fn entries(&self) -> &[Entry] {
		&self.entries
	}

	/// Resolve `name` (at `version`, or the **highest admitted version** when
	/// `None`) to its entry. Loud: an unknown name lists the available names, an
	/// unknown version lists the name's versions.
	pub fn entry(&self, name: &str, version: Option<u32>) -> Result<&Entry, LibraryError> {
		let of_name: Vec<&Entry> = self.entries.iter().filter(|e| e.name == name).collect();
		if of_name.is_empty() {
			let mut available: Vec<String> = self.entries.iter().map(|e| e.name.clone()).collect();
			available.dedup(); // entries are sorted by name
			return Err(LibraryError::UnknownPart { name: name.to_string(), available });
		}
		match version {
			// Entries are sorted by (name, version): the last one is the highest.
			None => Ok(of_name[of_name.len() - 1]),
			Some(v) => of_name.iter().find(|e| e.version == v).copied().ok_or_else(|| LibraryError::UnknownVersion {
				name: name.to_string(),
				version: v,
				available: of_name.iter().map(|e| e.version).collect(),
			}),
		}
	}

	/// Admit a candidate part. `part_json` is the full `.lmcpart` envelope text
	/// (see [`format::load_part`]); `meta` declares identity, provenance and the
	/// parameter interface. The candidate must pass the **admission gate** (see
	/// the [module docs](self)): build closed+manifold and volume-bit-
	/// deterministic at the defaults, every sampled range corner, and the
	/// midpoint. On success the part is stored canonically (re-serialized via
	/// [`format::save_part`], byte-stable) as `<name>-v<version>.lmcpart`, the
	/// index is rewritten, and the new [`Entry`] is returned. On failure NOTHING
	/// is admitted and the error names the exact problem — including, for gate
	/// failures, the failing sample's parameter values.
	pub fn add(&mut self, part_json: &str, meta: EntryMeta, opts: &AddOptions) -> Result<&Entry, AdmissionError> {
		let (document, _part_meta) = format::load_part(part_json).map_err(|error| AdmissionError::BadPart { error })?;
		validate_meta(&meta, &document, opts)?;
		if self.entries.iter().any(|e| e.name == meta.name && e.version == meta.version) {
			return Err(AdmissionError::DuplicateEntry { name: meta.name, version: meta.version });
		}

		let samples = run_gate(&document, &meta.param_interface, opts.corner_cap)?;

		let file = format!("{}-v{}.lmcpart", meta.name, meta.version);
		let part_path = self.dir.join(&file);
		// Canonical storage: re-serialized through the byte-stable saver, named
		// by the library identity (the envelope name a search/instantiate sees).
		std::fs::write(&part_path, format::save_part(&document, &meta.name))
			.map_err(|error| AdmissionError::Io { path: part_path.clone(), error })?;

		let mut tags = meta.tags;
		tags.sort();
		tags.dedup();
		let entry = Entry {
			name: meta.name,
			version: meta.version,
			category: meta.category,
			tags,
			description: meta.description,
			provenance: meta.provenance,
			param_interface: meta.param_interface,
			admitted: GateSummary { rebuilds: GATE_REBUILDS, corner_cap: opts.corner_cap, samples },
			file,
			deprecated: false,
		};
		let position = self.entries.partition_point(|e| (e.name.as_str(), e.version) < (entry.name.as_str(), entry.version));
		self.entries.insert(position, entry);
		if let Err((path, error)) = self.write_index() {
			// Keep memory consistent with disk: the entry is NOT admitted (the
			// orphaned part file is harmless and overwritten by a retry).
			self.entries.remove(position);
			return Err(AdmissionError::Io { path, error });
		}
		Ok(&self.entries[position])
	}

	/// Search the curated view: entries whose name/category/description/tags
	/// contain `text` (case-insensitive; empty matches all) AND carry every tag
	/// in `tags` (case-insensitive). **Deprecated entries are hidden** — resolve
	/// them explicitly via [`Library::entry`] / [`Library::instantiate`].
	/// Results keep the `(name, version)` order.
	pub fn search(&self, text: &str, tags: &[String]) -> Vec<&Entry> {
		let needle = text.to_lowercase();
		self.entries
			.iter()
			.filter(|e| !e.deprecated)
			.filter(|e| {
				let haystack = format!("{} {} {} {}", e.name, e.category, e.description, e.tags.join(" ")).to_lowercase();
				needle.is_empty() || haystack.contains(&needle)
			})
			.filter(|e| {
				tags.iter().all(|want| {
					let want = want.to_lowercase();
					e.tags.iter().any(|t| t.to_lowercase() == want)
				})
			})
			.collect()
	}

	/// Instantiate `name` (at `version`, default: highest) with the given
	/// parameter values: the stored part is loaded, the **interface defaults**
	/// are applied first, then the caller's `params` — each checked loudly
	/// against the declared interface ([`LibraryError::UnknownParam`]) and range
	/// ([`LibraryError::OutOfRange`], which also rejects non-finite values).
	/// A deprecated entry still instantiates but sets
	/// [`Instantiated::deprecated`] so the caller can warn. The document is NOT
	/// evaluated here — call [`Document::evaluate_brep`] / [`Document::mesh`]
	/// on the result.
	pub fn instantiate(&self, name: &str, version: Option<u32>, params: &BTreeMap<String, f64>) -> Result<Instantiated, LibraryError> {
		let entry = self.entry(name, version)?;
		let path = self.dir.join(&entry.file);
		let text = std::fs::read_to_string(&path).map_err(|error| LibraryError::Io { path: path.clone(), error })?;
		let (mut document, _) = format::load_part(&text).map_err(|error| LibraryError::BadStoredPart { path, error })?;
		for spec in &entry.param_interface {
			document.set_param(spec.name.clone(), spec.default);
		}
		for (param, &value) in params {
			let spec = entry.param_interface.iter().find(|s| &s.name == param).ok_or_else(|| LibraryError::UnknownParam {
				part: entry.name.clone(),
				param: param.clone(),
				interface: entry.param_interface.iter().map(|s| s.name.clone()).collect(),
			})?;
			// `!(>= && <=)` also rejects NaN/±inf loudly.
			if !(value >= spec.min && value <= spec.max) {
				return Err(LibraryError::OutOfRange {
					part: entry.name.clone(),
					param: param.clone(),
					value,
					min: spec.min,
					max: spec.max,
				});
			}
			document.set_param(param.clone(), value);
		}
		Ok(Instantiated { document, name: entry.name.clone(), version: entry.version, deprecated: entry.deprecated })
	}

	/// Deprecate every version of `name`: hidden from [`Library::search`],
	/// still on disk, still instantiable (with the [`Instantiated::deprecated`]
	/// warning), still resolvable by `.lmcasm` path references. Idempotent;
	/// returns how many versions are now deprecated. Loud on an unknown name.
	pub fn deprecate(&mut self, name: &str) -> Result<usize, LibraryError> {
		self.entry(name, None)?; // loud UnknownPart
		let before: Vec<bool> = self.entries.iter().map(|e| e.deprecated).collect();
		let mut count = 0;
		for entry in self.entries.iter_mut().filter(|e| e.name == name) {
			entry.deprecated = true;
			count += 1;
		}
		if let Err((path, error)) = self.write_index() {
			// Keep memory consistent with disk: the deprecation did not persist.
			for (entry, was) in self.entries.iter_mut().zip(before) {
				entry.deprecated = was;
			}
			return Err(LibraryError::Io { path, error });
		}
		Ok(count)
	}

	/// The `.lmcasm` files in the library directory (names sorted) that
	/// reference any of `name`'s part files by path — the dependents that make
	/// [`Library::remove`] refuse. An `.lmcasm` that cannot be parsed is a loud
	/// [`LibraryError::AsmUnreadable`] (a removal must not guess).
	pub fn dependents(&self, name: &str) -> Result<Vec<String>, LibraryError> {
		let files: BTreeSet<PathBuf> =
			self.entries.iter().filter(|e| e.name == name).map(|e| lexically_normalized(Path::new(&e.file))).collect();
		let read_dir = std::fs::read_dir(&self.dir).map_err(|error| LibraryError::Io { path: self.dir.clone(), error })?;
		let mut asm_files: Vec<PathBuf> = read_dir
			.filter_map(|r| r.ok().map(|d| d.path()))
			.filter(|p| p.extension().and_then(|e| e.to_str()) == Some("lmcasm"))
			.collect();
		asm_files.sort();
		let mut dependents = Vec::new();
		for asm in asm_files {
			let text = std::fs::read_to_string(&asm).map_err(|error| LibraryError::Io { path: asm.clone(), error })?;
			let value: serde_json::Value = serde_json::from_str(&text)
				.map_err(|e| LibraryError::AsmUnreadable { path: asm.clone(), reason: format!("not valid JSON: {e}") })?;
			let instances = value.get("instances").and_then(serde_json::Value::as_array);
			let references = instances.into_iter().flatten().any(|instance| {
				instance
					.get("source")
					.and_then(|s| s.get("path"))
					.and_then(serde_json::Value::as_str)
					.is_some_and(|p| files.contains(&lexically_normalized(Path::new(p))))
			});
			if references {
				dependents.push(asm.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default());
			}
		}
		Ok(dependents)
	}

	/// Remove every version of `name`: deletes the part files and index rows.
	/// Without `force` this first scans the directory's `.lmcasm` files and
	/// **refuses** with [`LibraryError::DependentsExist`] (naming them) when any
	/// still references the part by path. With `force` the scan is skipped and
	/// the removal proceeds — git history keeps it auditable and recoverable.
	/// Returns the removed part file names. Loud on an unknown name. (If the
	/// index rewrite itself fails mid-removal, the deleted files are already
	/// gone — instantiate then fails loudly on the stale row, and the next
	/// successful mutation, or git, restores consistency.)
	pub fn remove(&mut self, name: &str, force: bool) -> Result<Vec<String>, LibraryError> {
		self.entry(name, None)?; // loud UnknownPart
		if !force {
			let dependents = self.dependents(name)?;
			if !dependents.is_empty() {
				return Err(LibraryError::DependentsExist { name: name.to_string(), dependents });
			}
		}
		let removed: Vec<String> = self.entries.iter().filter(|e| e.name == name).map(|e| e.file.clone()).collect();
		for file in &removed {
			let path = self.dir.join(file);
			match std::fs::remove_file(&path) {
				Ok(()) => {}
				// Already gone is fine — the goal is its absence.
				Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
				Err(error) => return Err(LibraryError::Io { path, error }),
			}
		}
		self.entries.retain(|e| e.name != name);
		self.write_index().map_err(|(path, error)| LibraryError::Io { path, error })?;
		Ok(removed)
	}

	/// Rewrite `index.json` (sorted keys, entries sorted by `(name, version)`)
	/// — byte-stable: the same entries always produce identical bytes.
	fn write_index(&self) -> Result<(), (PathBuf, std::io::Error)> {
		let file = IndexFile {
			format: Some(LIBRARY_INDEX_FORMAT.to_string()),
			version: Some(LIBRARY_INDEX_VERSION),
			entries: self.entries.clone(),
		};
		let path = self.dir.join(INDEX_FILE);
		std::fs::write(&path, canonical_json(&file)).map_err(|error| (path.clone(), error))
	}
}

