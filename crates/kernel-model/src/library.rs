/// Validate name/version/interface/provenance before anything is built.
fn validate_meta(meta: &EntryMeta, document: &Document, opts: &AddOptions) -> Result<(), AdmissionError> {
	let bad = |reason: String| Err(AdmissionError::BadMeta { reason });
	let name_ok = !meta.name.is_empty()
		&& meta.name.len() <= 64
		&& meta.name.chars().next().is_some_and(|c| c.is_ascii_alphanumeric())
		&& meta.name.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-'));
	if !name_ok {
		return bad(format!(
			"name '{}' — must be 1–64 chars of A–Z a–z 0–9 . _ - and start alphanumeric (it becomes the stored file name)",
			meta.name
		));
	}
	if meta.version == 0 {
		return bad("version must be ≥ 1".to_string());
	}
	if opts.corner_cap < 2 {
		return bad(format!("corner_cap {} — the gate needs at least the all-min and all-max corners (≥ 2)", opts.corner_cap));
	}
	if meta.provenance.author.is_empty() || meta.provenance.date.is_empty() || meta.provenance.created_with.is_empty() {
		return bad(
			"provenance author/created_with/date must all be non-empty (the date is caller-supplied; this library never reads a clock)"
				.to_string(),
		);
	}
	let document_params: BTreeSet<&str> = document.params_iter().map(|(k, _)| k).collect();
	let mut seen = BTreeSet::new();
	for spec in &meta.param_interface {
		if spec.name.is_empty() {
			return bad("param_interface contains an empty parameter name".to_string());
		}
		if !seen.insert(spec.name.as_str()) {
			return bad(format!("param_interface declares '{}' twice", spec.name));
		}
		if spec.units.is_empty() {
			return bad(format!("parameter '{}': units must be declared (\"mm\", \"deg\", \"count\", …)", spec.name));
		}
		if !(spec.default.is_finite() && spec.min.is_finite() && spec.max.is_finite()) {
			return bad(format!("parameter '{}': default/min/max must all be finite", spec.name));
		}
		if spec.min > spec.max {
			return bad(format!("parameter '{}': min {} > max {}", spec.name, spec.min, spec.max));
		}
		if !(spec.default >= spec.min && spec.default <= spec.max) {
			return bad(format!("parameter '{}': default {} is outside [{}, {}]", spec.name, spec.default, spec.min, spec.max));
		}
		// A typo'd interface name would drive NOTHING (set_param would insert an
		// unused key and every sample would silently build the same shape).
		if !document_params.contains(spec.name.as_str()) {
			return bad(format!(
				"parameter '{}' is not in the part document's parameter table (document declares: {})",
				spec.name,
				if document_params.is_empty() {
					"none".to_string()
				} else {
					document_params.iter().copied().collect::<Vec<_>>().join(", ")
				}
			));
		}
	}
	Ok(())
}

/// The gate's sample plan: defaults, corners (capped), midpoint — deduplicated
/// by parameter values (a `min == max` parameter collapses corners), keeping
/// the first label.
fn gate_samples(interface: &[ParamSpec], corner_cap: usize) -> Vec<(String, BTreeMap<String, f64>)> {
	let mut plan: Vec<(String, BTreeMap<String, f64>)> = Vec::new();
	let push = |label: String, params: BTreeMap<String, f64>, plan: &mut Vec<(String, BTreeMap<String, f64>)>| {
		if !plan.iter().any(|(_, p)| *p == params) {
			plan.push((label, params));
		}
	};
	let defaults: BTreeMap<String, f64> = interface.iter().map(|s| (s.name.clone(), s.default)).collect();
	push("defaults".to_string(), defaults, &mut plan);

	let n = interface.len();
	if n > 0 {
		for corner in corner_masks(n, corner_cap) {
			let label: String = std::iter::once("corner_".to_string())
				.chain(corner.iter().map(|&high| if high { "h".to_string() } else { "l".to_string() }))
				.collect();
			let params: BTreeMap<String, f64> =
				interface.iter().zip(&corner).map(|(s, &high)| (s.name.clone(), if high { s.max } else { s.min })).collect();
			push(label, params, &mut plan);
		}
		let midpoint: BTreeMap<String, f64> = interface.iter().map(|s| (s.name.clone(), 0.5 * (s.min + s.max))).collect();
		push("midpoint".to_string(), midpoint, &mut plan);
	}
	plan
}

/// The corner combinations to sample: all `2^n` when they fit under `cap`,
/// else a deterministic spread of exactly `cap` corners — all-min, all-max,
/// each single parameter flipped high (from all-min) and flipped low (from
/// all-max) in interface order, then a Hamming-weight fill (every pair high,
/// every triple high, … lexicographically) until the cap is reached. The first
/// two corners always exercise every parameter at both extremes; the per-
/// parameter isolation corners cover as many leading parameters as fit.
fn corner_masks(n: usize, cap: usize) -> Vec<Vec<bool>> {
	if n < usize::BITS as usize && (1usize << n) <= cap {
		// Exhaustive: bit j of the counter = parameter j high.
		return (0..1usize << n).map(|mask| (0..n).map(|j| mask >> j & 1 == 1).collect()).collect();
	}
	fn push(mask: Vec<bool>, masks: &mut Vec<Vec<bool>>, cap: usize) {
		if masks.len() < cap && !masks.contains(&mask) {
			masks.push(mask);
		}
	}
	let mut masks: Vec<Vec<bool>> = vec![vec![false; n], vec![true; n]];
	for j in 0..n {
		for base in [false, true] {
			let mut mask = vec![base; n];
			mask[j] = !base;
			push(mask, &mut masks, cap);
		}
	}
	// Fill the remaining budget by Hamming weight: 2^n > cap here, and weights
	// 0..=n enumerate every corner, so the cap is always reached.
	let mut weight = 2;
	while masks.len() < cap && weight < n {
		let mut combo: Vec<usize> = (0..weight).collect();
		loop {
			let mut mask = vec![false; n];
			for &i in &combo {
				mask[i] = true;
			}
			push(mask, &mut masks, cap);
			if masks.len() == cap || !next_combination(&mut combo, n) {
				break;
			}
		}
		weight += 1;
	}
	masks
}

/// Advance `combo` (strictly increasing indices into `0..n`) to the next
/// lexicographic combination; `false` when exhausted.
fn next_combination(combo: &mut [usize], n: usize) -> bool {
	let w = combo.len();
	let mut i = w;
	while i > 0 {
		i -= 1;
		if combo[i] < n - w + i {
			combo[i] += 1;
			for k in i + 1..w {
				combo[k] = combo[k - 1] + 1;
			}
			return true;
		}
	}
	false
}

/// Render a sample for error messages: `label (k=v, …)`.
fn sample_string(label: &str, params: &BTreeMap<String, f64>) -> String {
	if params.is_empty() {
		return label.to_string();
	}
	let body: Vec<String> = params.iter().map(|(k, v)| format!("{k}={v}")).collect();
	format!("{label} ({})", body.join(", "))
}

/// Run the admission gate (see the [module docs](self)) and return the
/// per-sample evidence, or the loud error naming the failing sample.
fn run_gate(document: &Document, interface: &[ParamSpec], corner_cap: usize) -> Result<Vec<GateSample>, AdmissionError> {
	let mut samples = Vec::new();
	for (label, params) in gate_samples(interface, corner_cap) {
		let sample = || sample_string(&label, &params);
		let mut doc = document.clone();
		for (k, &v) in &params {
			doc.set_param(k.clone(), v);
		}
		let mut volumes = [0.0f64; GATE_REBUILDS as usize];
		let mut faces = 0;
		let mut genus = 0;
		let mut shells = 0;
		for volume in &mut volumes {
			// A FULL fresh evaluation each round — the determinism this proves is
			// the rebuild's, not a cache's (a Document caches no geometry).
			let solid = doc.evaluate_brep().ok_or_else(|| AdmissionError::GateBuildFailed {
				sample: sample(),
				reason: "the feature tree produced no exact B-rep at these values (missing feature, cyclic reference, or a voxel-half-only feature)".to_string(),
			})?;
			if solid.face_count() == 0 {
				return Err(AdmissionError::GateBuildFailed {
					sample: sample(),
					reason: "the rebuild produced an EMPTY solid — the dimensions degenerate at these values (e.g. a cut consumes the whole body)".to_string(),
				});
			}
			let validity = kernel_brep::validate(&solid);
			if !(validity.closed && validity.manifold) {
				return Err(AdmissionError::GateInvalid {
					sample: sample(),
					closed: validity.closed,
					manifold: validity.manifold,
					genus: validity.genus,
					shells: validity.shells,
				});
			}
			*volume = kernel_brep::volume(&solid);
			if !volume.is_finite() {
				return Err(AdmissionError::GateBuildFailed {
					sample: sample(),
					reason: format!("the rebuild's volume is not finite ({volume})"),
				});
			}
			faces = solid.face_count();
			genus = validity.genus;
			shells = validity.shells;
		}
		if let Some(&second) = volumes.iter().find(|v| v.to_bits() != volumes[0].to_bits()) {
			return Err(AdmissionError::GateNondeterministic { sample: sample(), first_volume: volumes[0], second_volume: second });
		}
		samples.push(GateSample { label, params, volume: volumes[0], faces, genus, shells });
	}
	Ok(samples)
}

/// Lexically normalize a relative path: drop `.` components and resolve `..`
/// against preceding components (purely textual — no filesystem access), so
/// `"./x.lmcpart"` and `"sub/../x.lmcpart"` both compare equal to
/// `"x.lmcpart"` in the dependents scan.
fn lexically_normalized(path: &Path) -> PathBuf {
	let mut out = PathBuf::new();
	for component in path.components() {
		match component {
			Component::CurDir => {}
			Component::ParentDir => {
				if !out.pop() {
					out.push("..");
				}
			}
			other => out.push(other),
		}
	}
	out
}

